function makePrisma_(p: jest.Mocked<PrismaService>): jest.Mocked<PrismaService> {
  return p;
}

/**
 * Flushes N microtask ticks. The dispatchOne pipeline (subscribe -> $transaction
 * -> scan.create -> scanJob.create -> queue.add -> awaitScanJobCompletion's
 * Promise constructor) has a non-trivial number of awaits, so tests need to
 * yield enough times for the pollTimer + budgetTimer to be installed before
 * advancing the fake clock.
 */
async function flushMicrotasks(n = 10): Promise<void> {
  for (let i = 0; i < n; i++) {
    await Promise.resolve();
  }
}
