type TemplateRun = {
  id: string;
  templateId: string;
  templateName: string;
  engagementId: string;
  target: string;
  status: 'PENDING' | 'RUNNING' | 'COMPLETED' | 'FAILED' | 'CANCELLED';
  currentStepIndex: number;
  startedAt: Date | null;
  completedAt: Date | null;
  errorMessage: string | null;
  createdById: string;
  createdAt: Date;
  updatedAt: Date;
};

function makeRun(overrides: Partial<TemplateRun> = {}): TemplateRun {
  return {
    id: 'run_1',
    templateId: 'tpl_1',
    templateName: 'recon-passive',
    engagementId: 'eng_1',
    target: 'example.com',
    status: 'RUNNING',
    currentStepIndex: 0,
    startedAt: new Date(),
    completedAt: null,
    errorMessage: null,
    createdById: 'user_1',
    createdAt: new Date(),
    updatedAt: new Date(),
    ...overrides,
  };
}

function makePrisma(): jest.Mocked<PrismaService> {
  const prisma = {
    subdomain: {
      findMany: jest.fn().mockResolvedValue([]),
    },
    ipAddress: {
      findMany: jest.fn().mockResolvedValue([]),
    },
    scan: {
      create: jest
        .fn()
        .mockImplementation(({ data }: { data: Record<string, unknown> }) =>
          Promise.resolve({ id: 'scan_1', ...data }),
        ),
    },
    scanJob: {
      // `id` defaults to a random UUID generated by StepExecutor; tests that
      // care about the id assert against the `data.id` echoed back here, or
      // against the `scanJobId` payload sent to the BullMQ queue.
      create: jest
        .fn()
        .mockImplementation(({ data }: { data: Record<string, unknown> }) =>
          Promise.resolve({ status: 'PENDING', ...data }),
        ),
      findUnique: jest.fn().mockResolvedValue(null),
    },
    // C2: dispatchOne wraps scan+scanJob creation in a single $transaction.
    // The mock just invokes the callback with `prisma` itself as the tx
    // client so `tx.scan.create` / `tx.scanJob.create` route to the same
    // jest.fn() instances asserted by the existing specs.
    $transaction: jest.fn(async (cb: (tx: unknown) => Promise<unknown>) => cb(prisma)),
  } as unknown as jest.Mocked<PrismaService>;
  return prisma;
}

function makeRedis(): jest.Mocked<OrchestratorRedisSubscriber> {
  return {
    subscribe: jest.fn().mockResolvedValue(undefined),
    unsubscribe: jest.fn().mockResolvedValue(undefined),
    on: jest.fn(),
    off: jest.fn(),
    quit: jest.fn().mockResolvedValue(undefined),
  } as unknown as jest.Mocked<OrchestratorRedisSubscriber>;
}

function makeScannerRegistry(timeoutMs = 600_000): ScannerRegistry {
  return {
    get: jest.fn().mockReturnValue({
      name: 'subfinder',
      docker: { defaultTimeoutMs: timeoutMs },
    }),
  } as unknown as ScannerRegistry;
}

function makeScanQueue(): jest.Mocked<Queue<ScanJobPayload>> {
  return {
    add: jest.fn().mockResolvedValue({}),
  } as unknown as jest.Mocked<Queue<ScanJobPayload>>;
}

function build(
  prisma: jest.Mocked<PrismaService>,
  registry: ScannerRegistry,
  queue: jest.Mocked<Queue<ScanJobPayload>>,
  redis: jest.Mocked<OrchestratorRedisSubscriber>,
  pollIntervalMs = 5_000,
): StepExecutor {
  const ctxBuilder = new ContextBuilder(prisma);
  return new StepExecutor(prisma, registry, queue, redis, ctxBuilder, { pollIntervalMs });
}

